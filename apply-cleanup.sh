# 1차 발표 (2026.07.08) — SAP S/4HANA 도입 프로젝트: C-Nergy

> CODE Academy CL2 1기 · 반 내 경쟁(4개 팀, 30명) 발표본 · **반 1등(우수상) 수상**
> 팀원: 강효창, 류우석, 박가을, 엄영욱, 이상윤, 정나연, 최지수

## 기업 소개 — C-Nergy (No.1 Crude oil processing & export company)

에너지의 흐름을 데이터로 연결하는 가상 정유기업 C-Nergy를 대상으로 SAP S/4HANA 도입 프로젝트를 진행했습니다.

- 기업 설립: 2004년
- 매출액: 2,000억원+
- 직원 수: 2,500명+
- 주요 사업: 원유 정제 사업, 석유화학 제품 생산, 전국 물류 공급망 연결, 에너지 데이터 기반 생산 최적화

## 정유 산업의 특징

**주요 6가지 연산품**: 아스팔트(Asphalt), 제트유(Jet Fuel), LPG, 경유(Diesel), 휘발유(Gas Fuel), 나프타(Naphtha) — 원유 한 배치를 정제하면 이 6개 제품이 동시에 산출되는 연산품(Co-product) 구조입니다.

**원유 수입 구조**: 미국·멕시코·두바이 등 해외 공급업체로부터 달러(USD) 기준으로 원유를 수입하며, 환율 변동이 원가에 직접 반영됩니다.

**운송 프로세스**: 중동 Dubai에서 대한민국 서산까지 원유 운송에 약 30~45일이 소요됩니다.

## Process Flow

MM(구매)→PP(생산)→SD(판매)→FI/CO(재무/원가)로 이어지는 전사 End-to-End 프로세스입니다.

- **MM**: 구매 원유 선택 → 구매 오더/서비스 오더 → 구매 결재 → 선적 입고 승인 → 선적 입고 → 부피 측정 → 송장 → 지급 및 반제 처리(FI 연동) → 플랜트 입고 승인 → 플랜트 입고 → 부피 측정 → 증발 손실 처리 → 전처리 공정(PP로 이관)
- **PP**: 전처리 공정 → 수요 계획 수립 ↔ PIR 조정 → 공정 시뮬레이션(CO 연동) → 자재소요계획 → 생산 오더 → 원자재 출고/반제품 출고 → 반제품 입고/완제품 입고 → 공정 및 원가 분석(CO) → 전표 생성(FI)
- **SD**: 완제품 출하 → 물류 센터 입고 → 판매 오더 → 자재 소요 계획 → (당월 재고로 차월 수요 충족 여부 판정 → 미충족 시 재고 보충 요청 → 운송 계획으로 순환) → 출고 → 송장 → 입금
- **FI**: 구매/생산/판매 각 단계에서 발생하는 전표(지급 및 반제 처리, 전표 생성)를 연동 처리
- **CO**: 공정 시뮬레이션, 공정 및 원가 분석을 통해 PP·MM 데이터를 원가 정보로 환산

## Business Challenge — 5대 Pain Point와 Solution

### [1] 외환 변동 및 연산품 원가 배분 복잡성 (Exchange Rate & Product Mix Volatility)

시장 가격이 변동할 때 어떤 제품의 생산 비중을 조정해야 수익이 극대화되는지에 대한 데이터가 부족했습니다.

- **Solution 1**: 시장 가격 변화에 대응하여 계절별 수요를 조정 (FIORI BOM 조회 프로그램 `ZPB1PP02`) — 계절(봄/여름/가을/겨울)에 따라 원유 대비 연산품 산출 비율이 달라지는 역BOM 데이터를 실시간 조회
- **Solution 2**: 당일 국제유가/환율을 적용해 실무자가 급변한 시장 상황에 직접 대응 (배치 프로그램 `ZB1MM_YSSCURRENCY`, PIR 프로그램 `ZRB1PP0002`) — 외부 환율·MOPS 국제 제품가 API를 연동해 매일 환율/시세 데이터를 자동 삽입
- **Solution 3**: 내부 로직을 수행하여 원유 투입 및 연산품 산출량을 자동 계산 (MRP 프로그램 `ZRB1MM0004`) — BOM과 PIR을 고려해 최소 원유 투입량을 산정하고 일자별 반제품/완제품 생산량을 순방향 계산

### [2] 제품이 동시에 쏟아지는 공정의 관리 한계 (Simultaneous Multi-Product Process)

원유 한 배치를 정제하면 LPG(가스, 40℃ 미만)·휘발유(40~200℃)·등유/제트유(150~250℃)·경유(200~350℃)·중유(250~400℃)·잔사유/아스팔트(350℃ 초과)가 동시에 산출되어, 완제품 하나만 생산할 수 없고 재고 관리가 어렵다는 정유 공정 특유의 문제가 있습니다.

### [3] 입고 물량 계량 차이 및 실재고 불일치 (Inventory Loss & Stock Mismatch)

원유·석유제품은 온도 변화에 따른 부피 팽창/수축과 운송 중 자연 증발 손실이 발생합니다(예: 400,000 BBL 선적 → 399,800 BBL 입고, -200 BBL 손실). 이 손실이 장부에 정산되지 않으면 장부 재고와 실제 재고 간 불일치가 생겨 단가 산정·가격 책정이 어려워집니다.

- **Solution 1**: 15℃ 기준 배럴로 통일하고 공급망 전 과정의 부피 측정을 자동화 (부피 측정·출고 관리 프로그램 `ZPB1MM04`, `SAPMZB1SD0001`) — 실측 온도·밀도로 환산 부피(15℃ 기준)를 자동 계산해 실측치와 환산치 차이(변화량)를 표시
- **Solution 2**: 보정계수를 바탕으로 구매오더 입고와 판매오더 출고 시 실측 부피를 환산 부피로 계산해 반영
- **Solution 3**: 입고 처리 시 증발 손실에 대한 자재 마스터 업데이트, 전표 처리를 통한 증발 손실 정산 (재고 현황 관리 프로그램 `ZPB1MM05`, 전표 대시보드 프로그램 `ZRB1FI0001`) — 재고 수량/총평가금액/단가 변화 타임라인을 손실처리 유형으로 추적하고 관련 회계전표를 자동 생성

### [4] 품질 서비스와 공정 제어 시스템 간 연동 부재 (Quality Service & Control System Disconnect)

품질 분석 결과가 생산시스템과 분리되어 있어 기준 미달 원료가 공정에 투입되는 것을 시스템적으로 차단하지 못했습니다.

- **Solution**: 재고 유형을 분리하여 기준 미달 물량의 즉시 출고를 제한 (재고 현황 관리 프로그램 `ZPB1MM05`) — 전처리 공정 개시/성공/실패 이력을 재고 유형별로 추적하고, 실패 시 불용재고로 즉시 격리해 후속 공정 투입을 차단, 가용 재고만 승인되어 다음 공정으로 넘어가도록 설계

### [5] 현장 모바일 연동 부재 및 데이터 단절 (Mobile Field Connectivity)

모바일 기기를 통한 현장 데이터 입력이 불가능해 현장 재고와 전산 재고 간 시차가 발생했습니다.

- **Solution**: FIORI 모바일 화면을 구현해 재고 보충 문서·주문오더 문서를 현장에서 즉시 생성 (모바일 재고 보충 문서 생성 및 즉시 출하 프로그램 `ZPB1SD04`, 모바일 주문 생성 프로그램 `ZPB1SD01`)

## 프로젝트 시연 영상

C-Nergy의 원유 도입 경로(미국·멕시코·중동에서 대한민국 서산까지)를 지도로 시각화한 화면을 포함해, 구매→생산→판매→재무 전체 프로세스를 실제 화면으로 시연했습니다.

## 자체 평가 의견

**완성도 평가**: 데이터 초기화 및 테스트 과정에서 발생한 오차를 CBO 프로그램으로 추적하여 원인을 규명했습니다. 각 프로그램의 완성도와 짜임새가 우수하며, 비정상 데이터 오류를 잡아낼 만큼 민감하고 정교하게 설계했습니다.

**주요 개발 이슈**: 각 프로세스는 당일 자재 단가를 기반으로 처리되는 구조이며, 이전 프로세스가 모두 완료되어야 다음 프로세스가 진행 가능하도록 설계했습니다. 이 때문에 예시 데이터의 생성과 검토에 많은 시간을 투자하며 프로세스 전체 흐름을 검증했습니다.

**프로젝트 소감**: 초기에는 기준 통화만 DB 필드로 정의하고 거래 통화는 환율로 계산하던 구조였는데, 달러와 원화의 소수점 자릿수 차이로 인한 오차가 발생했습니다. 신규 테이블을 정의해 문제를 해결하며 설계의 중요성을 재확인했습니다.
